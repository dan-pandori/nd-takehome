#!/usr/bin/env python3
"""Post-hoc mechanism counts of run olmo-answeronly (not pre-registered). Reach-41, rl traces.
  - contains: the sampled answer contains the trace's own final answer verbatim (whitespace-collapsed substring);
    split by strict success;
  - draft: traces.csv draft_k > 0 (the final answer's first 40 characters appear in the thinking: olmo-transplant's
    draft covariate); strict rate per writer and condition split by it (sample-pooled);
  - zero prompts: reach prompts with genuine rate 0 per writer and condition (results.csv).
Writes olmo_answeronly/mechanism.md."""
import collections
import csv
import sys

sys.path.insert(0, "olmo_answeronly")
from analyze import INP, A, answer, iter_gz, wsnorm  # noqa: E402

tr = {t["trace"]: t for t in csv.DictReader(open("olmo_transplant/traces.csv")) if t["kind"] == "rl" and t["set"] == "reach"}
src = {}
need = {(t["job"], t["pid"], int(t["chunk"]), int(t["i"])): k for k, t in tr.items()}
for jb in ("F_s2300_ifb", "C1_s2300_ifb"):
    for r in iter_gz(f"{INP}/{jb}.jsonl.gz"):
        k = (jb, r["pid"], r["chunk"], r["i"])
        if k in need:
            src[need[k]] = wsnorm(r["text"].split("</think>", 1)[1])
c = collections.defaultdict(collections.Counter)
jobs = [("R_dpo", f"{A}/samples/R_dpo.jsonl.gz", f"{A}/graded/R_dpo.jsonl"),
        ("R_s2300", f"{A}/samples/R_s2300.jsonl.gz", f"{A}/graded/R_s2300.jsonl"),
        ("tp_R_dpo", f"{INP}/tp_R_dpo.jsonl.gz", f"{INP}/tp_R_dpo_graded.jsonl"),
        ("tp_R_s2300", f"{INP}/tp_R_s2300.jsonl.gz", f"{INP}/tp_R_s2300_graded.jsonl"),
        ("L1_lora", f"{A}/samples/L1_lora.jsonl.gz", f"{A}/graded/L1_lora.jsonl")]
import json  # noqa: E402
for job, sf, gf in jobs:
    g = {}
    for ln in open(gf):
        x = json.loads(ln)
        g[f"{x['rid']}|{x['i']}"] = x["strict"]
    for r in iter_gz(sf):
        if r["trace"] not in tr or r["cond"] not in ("T1", "T2", "A1", "A2", "A3", "A4", "L1"):
            continue
        k = (r["writer"], r["cond"])
        st = g[f"{r['rid']}|{r['i']}"]
        a = answer("</think>" + r["text"])
        has = src[r["trace"]] in a
        d = tr[r["trace"]]["draft_k"] not in ("", "0")
        c[k]["n"] += 1
        c[k]["strict"] += st
        c[k]["contains"] += has
        c[k]["contains_fail"] += has and not st
        c[k][f"n_draft{d}"] += 1
        c[k][f"s_draft{d}"] += st
res = list(csv.DictReader(open("olmo_answeronly/results.csv")))
L = ["# olmo-answeronly mechanism counts (post hoc; generated by olmo_answeronly/mechanism.py)", "",
     "Reach-41, all 115 rl traces x 8. T1 / T2 = olmo-transplant's samples. Strict grades. `draft` = the trace's thinking "
     "contains the final answer's opening (92 of 115 traces).", "",
     "| writer | cond | samples | strict | contain the trace's answer verbatim | of those, fail | strict, draft in thinking | "
     "strict, no draft in thinking | prompts with genuine 0 |", "|---|---|---|---|---|---|---|---|---|"]
for (w, cd), v in sorted(c.items(), key=lambda x: (x[0][0], x[0][1])):
    z = sum(1 for r in res if r["set"] == "reach" and r["writer"] == w and r["cond"] == cd and r["genuine_rate"] not in ("",)
            and float(r["genuine_rate"]) == 0)
    L.append(f"| {w} | {cd} | {v['n']} | {v['strict']} ({v['strict'] / v['n']:.3f}) | {v['contains']} | {v['contains_fail']} | "
             f"{v['s_draftTrue']} / {v['n_draftTrue']} ({v['s_draftTrue'] / v['n_draftTrue']:.3f}) | "
             f"{v['s_draftFalse']} / {v['n_draftFalse']} ({v['s_draftFalse'] / v['n_draftFalse']:.3f}) | {z} |")
open("olmo_answeronly/mechanism.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
