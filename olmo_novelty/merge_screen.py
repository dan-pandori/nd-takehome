#!/usr/bin/env python3
"""Merge the agents' screened rows into screened.md and to_add_to_zotero.md (run olmo-novelty).

usage: python3 olmo_novelty/merge_screen.py   (reads olmo_novelty/screen/*.tsv, not *_relations.tsv)
One row per source (arXiv id without version, or title for non-arXiv sources); depth = deepest reading; relevance =
max; agents = who screened it. Sources already in references.bib are marked and left out of the Zotero list."""
import csv, glob, os, re, collections
HERE = os.path.dirname(os.path.abspath(__file__))
BIB = os.path.expanduser('~/nd-rl/references.bib')
ORDER = ['title', 'abstract', 'skim', 'in-depth', 'full']

def key(r):
    i = (r.get('id') or '').strip()
    m = re.search(r'(\d{4}\.\d{4,5})', i)
    if m and not i.lower().startswith(('hf:', 'lesswrong', 'acl:', 'github')):
        return m.group(1)
    return i.lower() or (r.get('title') or '').strip().lower()[:60]

def main():
    bib = open(BIB).read() if os.path.exists(BIB) else ''
    in_bib = set(re.findall(r'(\d{4}\.\d{4,5})', bib))
    rows = []
    for p in sorted(glob.glob(os.path.join(HERE, 'screen', '*.tsv'))):
        if p.endswith('_relations.tsv'):
            continue
        a = os.path.basename(p)[:-4]
        for r in csv.DictReader(open(p), delimiter='\t', quoting=csv.QUOTE_NONE):
            r['_a'] = a; rows.append(r)
    u = collections.OrderedDict()
    for r in rows:
        u.setdefault(key(r), []).append(r)
    out = []
    for k, v in u.items():
        d = max(v, key=lambda x: ORDER.index(x['depth'].strip()) if x['depth'].strip() in ORDER else 0)
        rel = max(int(x['relevance']) if x['relevance'].strip().isdigit() else 0 for x in v)
        prior = 'yes' if any(x['prior'].strip().lower() == 'yes' for x in v) else 'no'
        out.append(dict(id=k, version=d['version'].strip(), title=d['title'].strip(), author=d['first_author'].strip(),
                        date=d['date'].strip(), prior=prior, depth=d['depth'].strip(), rel=rel,
                        topic=';'.join(sorted({t for x in v for t in x['topic'].replace(' ', '').split(';') if t})),
                        bears=';'.join(sorted({t for x in v for t in x['bears_on'].replace(' ', '').split(';') if t})),
                        agents='+'.join(sorted({x['_a'] for x in v})), line=d['one_line'].strip(),
                        bib='yes' if k in in_bib else 'no'))
    out.sort(key=lambda o: (-o['rel'], -(ORDER.index(o['depth']) if o['depth'] in ORDER else 0), o['id']))
    dep = collections.Counter(o['depth'] for o in out)
    new = sum(o['prior'] == 'no' for o in out)
    with open(os.path.join(HERE, 'screened.md'), 'w') as fh:
        fh.write('# Screened sources — olmo-novelty (2026-11-07)\n\n')
        fh.write(f'{len(out)} distinct sources ({new} new to the four earlier reviews, {len(out) - new} "prior"); '
                 f'depth: ' + ', '.join(f'{k} {dep[k]}' for k in ORDER if dep[k]) + '. Generated by '
                 '`merge_screen.py` from `screen/*.tsv` (one file per agent: PR ProRL family, IL critics, IF '
                 'instruction following, DT domains and trajectories, GG gaming and grading, NV fresh novelty '
                 'search). Relevance 0–3; `bears on` = our claims C1–C8; questions Q1–Q6 as in the brief. '
                 'Sorted by relevance, then depth.\n\n')
        fh.write('| # | id | title | first author | date | prior | depth | rel. | topic | bears on | agents | one line |\n')
        fh.write('|---|---|---|---|---|---|---|---|---|---|---|---|\n')
        for n, o in enumerate(out, 1):
            t = o['title'].replace('|', '/'); l = o['line'].replace('|', '/')
            idv = o['id'] + (o['version'] if o['version'] and o['version'].startswith('v') else '')
            fh.write(f"| {n} | {idv} | {t} | {o['author']} | {o['date']} | {o['prior']} | {o['depth']} | {o['rel']} | "
                     f"{o['topic']} | {o['bears']} | {o['agents']} | {l} |\n")
    z = [o for o in out if o['bib'] == 'no' and (o['rel'] >= 2 or o['depth'] in ('in-depth', 'full'))]
    with open(os.path.join(HERE, 'to_add_to_zotero.md'), 'w') as fh:
        fh.write('# Papers to add to Zotero (run olmo-novelty, 2026-11-07)\n\n')
        fh.write('One identifier per line, for Dan, in the order of `screened.md`: every source read in depth and '
                 'every source of relevance ≥ 2 that is not already in `references.bib` (Yue et al. 2504.13837 and '
                 'ProRL 2505.24864 are). Citekeys in `notes/` are proposals; pin them in Zotero or rename them in '
                 'the notes after import. Non-arXiv sources are given by URL or venue id.\n\n')
        for o in z:
            fh.write((f"arxiv:{o['id']}" if re.fullmatch(r'\d{4}\.\d{4,5}', o['id']) else o['id']) + '\n')
    print(len(out), 'sources;', new, 'new;', dict(dep), ';', len(z), 'for Zotero')

if __name__ == '__main__':
    main()
