#!/usr/bin/env python3
"""Theorem-level necessity: does every proof within the bound need a given rule?  (run proof-strategies)

BanSearch = minlen.Search with a rule ban; its _search is minlen.Search._search COPIED VERBATIM (generated by a script
from minlen.py at this commit) with exactly five guards added: BOTE, IMPI, NEGI (which also disables minlen's reductio
template, as that template ends in NEGI + DN), ORE; DN uses minlen's own forbid ('DN', which disables DN and the
reductio template).  Same restricted formula space as minlen (subformulas of the theorem, their negations and double
negations), so "requires" means: requires, within this space and bound (necessity.py's convention).

  python3 proof_strategies/necessity_ps.py --in SET.jsonl --out OUT.jsonl --bans ORE NEGI BOTE DN --bound 12 --time 60 \
      --procs 32 [--sample 600 --strata n_lines --seed 0]
Per theorem: unrestricted search (n0) then one restricted search per ban.  requires[X] = n0 found and the X-banned search
finds no proof within the bound and does not time out.  Found proofs are written out for a Lean check (VPS).
"""
import argparse, collections, gzip, json, os, random, sys, time
from multiprocessing import Pool
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
import minlen                                              # noqa: E402
from minlen import BOT, Timeout                            # noqa: E402


class BanSearch(minlen.Search):
    def __init__(self, prem, concl, ban=(), **kw):
        forbid = ('DN',) if 'DN' in ban else ()
        super().__init__(prem, concl, forbid=forbid, **kw)
        self.ban = set(ban)

    def _search(self, G, A, b, d=0, H=frozenset()):
        bestc, bestt = b + 1, None
        can_box = self.max_depth is None or d < self.max_depth

        def consider(c, t):
            nonlocal bestc, bestt
            if c < bestc:
                bestc, bestt = c, t

        # one-step rules from available formulas first (cheap)
        # ANDE
        if b >= 1:
            for C in self.conj:
                if C[1] == G or C[2] == G:
                    if self.ctx_neg and ('#neghyp', C) in H:
                        continue
                    r = self.inp(C, A, min(b, bestc) - 1, d, H)
                    if r:
                        consider(r[0] + 1, ('ANDE1' if C[1] == G else 'ANDE2', G, r[1]))
        # IMPE
        if b >= 1:
            for I in self.imps:
                if I[2] == G:
                    r = self.inp(I, A, min(b, bestc) - 1, d, H)
                    if r:
                        r2 = self.inp(I[1], A | {I}, min(b, bestc) - 1 - r[0], d, H)
                        if r2:
                            consider(r[0] + r2[0] + 1, ('IMPE', G, r[1], r2[1]))
        # DN
        if b >= 1 and not self.forbid_dn:
            nn = ('not', ('not', G))
            r = self.inp(nn, A, min(b, bestc) - 1, d, H)
            if r:
                consider(r[0] + 1, ('DN', G, r[1]))
        # BOTE
        if G != BOT and b >= 1 and 'BOTE' not in self.ban:
            r = self.inp(BOT, A, min(b, bestc) - 1, d, H)
            if r:
                consider(r[0] + 1, ('BOTE', G, r[1]))
        # intro rules
        if G[0] == 'and' and b >= 1:
            r = self.inp(G[1], A, min(b, bestc) - 1, d, H)
            if r:
                r2 = self.inp(G[2], A | {G[1]}, min(b, bestc) - 1 - r[0], d, H)
                if r2:
                    consider(r[0] + r2[0] + 1, ('ANDI', G, r[1], r2[1]))
        if G[0] == 'or' and b >= 1:
            r = self.inp(G[1], A, min(b, bestc) - 1, d, H)
            if r:
                consider(r[0] + 1, ('ORI1', G, r[1]))
            r = self.inp(G[2], A, min(b, bestc) - 1, d, H)
            if r:
                consider(r[0] + 1, ('ORI2', G, r[1]))
        if G[0] == 'imp' and b >= 2 and 'IMPI' not in self.ban:
            a, c = G[1], G[2]
            if a == c and can_box:
                consider(2, ('IMPI', G, a, None))
            elif b >= 3 and can_box:
                r = self.best(c, A | {a}, min(b, bestc) - 2, d + 1, H | {a} | ({('#impi',)} if self.ctx_impi else set()))
                if r:
                    consider(r[0] + 2, ('IMPI', G, a, r[1]))
        if G[0] == 'not' and b >= 3 and can_box and 'NEGI' not in self.ban:
            r = self.best(BOT, A | {G[1]}, min(b, bestc) - 2, d + 1, H | {G[1]} | ({('#neghyp', G[1])} if self.ctx_neg else set()))
            if r:
                consider(r[0] + 2, ('NEGI', G, G[1], r[1]))
        if G == BOT and b >= 1:
            for X in self.S:
                NX = ('not', X)
                if NX not in self.S and NX not in A:
                    continue
                if NX in A:
                    r = self.inp(X, A, min(b, bestc) - 1, d, H)
                    if r:
                        consider(r[0] + 1, ('NEGE', BOT, r[1], ('R0', NX)))
                elif X in A:
                    r = self.inp(NX, A, min(b, bestc) - 1, d, H)
                    if r:
                        consider(r[0] + 1, ('NEGE', BOT, ('R0', X), r[1]))
                else:
                    r = self.inp(X, A, min(b, bestc) - 2, d, H)
                    if r:
                        r2 = self.inp(NX, A | {X}, min(b, bestc) - 1 - r[0], d, H)
                        if r2:
                            consider(r[0] + r2[0] + 1, ('NEGE', BOT, r[1], r2[1]))
        # classical reductio: assume ~G, derive F, NEGI -> ~~G, DN
        if G != BOT and G[0] != 'not' and b >= 4 and can_box and not self.forbid_dn and 'NEGI' not in self.ban:
            r = self.best(BOT, A | {('not', G)}, min(b, bestc) - 3, d + 1, H | {('not', G)})
            if r:
                consider(r[0] + 3, ('RAA', G, r[1]))
        # ORE over a disjunction in S
        if b >= 3 and can_box and not (self.ctx_impi and ('#impi',) in H) and not (self.ctx_ore and ('#ore',) in H) and 'ORE' not in self.ban:
            for D in self.disj:
                if D == G:
                    continue
                if self.ore_mode == 'loose' and D not in self.prem:
                    continue
                if self.ore_mode == 'strict' and D not in self.prem and D not in H and D[1] != D[2]:
                    continue
                r = self.inp(D, A, min(b, bestc) - 3, d, H)
                if not r:
                    continue
                a, c = D[1], D[2]
                A2 = A | {D}
                ca = (1, None) if a == G else None
                if ca is None:
                    ra = self.best(G, A2 | {a}, min(b, bestc) - r[0] - 3, d + 1, H | {a} | ({('#ore',)} if self.ctx_ore else set()))
                    ca = (ra[0] + 1, ra[1]) if ra else None
                if ca is None:
                    continue
                cb = (1, None) if c == G else None
                if cb is None:
                    rb = self.best(G, A2 | {c}, min(b, bestc) - r[0] - ca[0] - 1, d + 1, H | {c} | ({('#ore',)} if self.ctx_ore else set()))
                    cb = (rb[0] + 1, rb[1]) if rb else None
                if cb is None:
                    continue
                consider(r[0] + ca[0] + cb[0] + 1, ('ORE', G, r[1], a, ca[1], c, cb[1]))
        # lemma: derive some L in S first, then G with L available
        if self.lemmas and b >= 2:
            for L in self.S:
                if L in A or L == G:
                    continue
                r = self.best(L, A, min(b, bestc) - 1, d, H)
                if not r:
                    continue
                r2 = self.best(G, A | {L}, min(b, bestc) - r[0], d, H)
                if r2:
                    consider(r[0] + r2[0], ('LEMMA', G, L, r[1], r2[1]))
        return (bestc, bestt) if bestt is not None else None



def solve(prem, concl, ban, bound, tl):
    if concl in prem:
        return {'n': len(prem) if prem[-1] == concl else len(prem) + 1, 'timeout': False, 'proof': None, 'trivial': True}
    s = BanSearch(prem, concl, ban=ban, deadline=time.time() + tl, lemmas=True)
    try:
        r = s.run(bound)
    except Timeout:
        return {'n': None, 'timeout': True, 'proof': None}
    return {'n': r[0] if r else None, 'timeout': False, 'proof': r[1] if r else None}


def work(args):
    rec, bans, bound, tl = args
    t0 = time.process_time()
    prem, concl = minlen.parse_thm(rec['prompt'])
    out = {'name': rec.get('name'), 'prompt': rec['prompt'], 'src_index': rec['_i']}
    out['free'] = solve(prem, concl, (), bound, tl)
    out['ban'] = {}
    for b in bans:
        out['ban'][b] = solve(prem, concl, (b,), bound, tl) if out['free']['n'] is not None else None
    out['requires'] = {b: (out['free']['n'] is not None and out['ban'][b] is not None and out['ban'][b]['n'] is None
                           and not out['ban'][b]['timeout']) for b in bans}
    out['secs'] = round(time.process_time() - t0, 3)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--in', dest='inp', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--bans', nargs='+', default=['ORE', 'NEGI', 'BOTE', 'DN'])
    ap.add_argument('--bound', type=int, default=12)
    ap.add_argument('--time', type=float, default=60)
    ap.add_argument('--procs', type=int, default=2)
    ap.add_argument('--sample', type=int, default=0)
    ap.add_argument('--strata', default=None)
    ap.add_argument('--seed', type=int, default=0)
    a = ap.parse_args()
    op = (lambda f: gzip.open(f, 'rt')) if a.inp.endswith('.gz') else open
    recs = []
    for i, line in enumerate(op(a.inp)):
        r = json.loads(line)
        r.setdefault('name', f'{os.path.basename(a.inp).split(".")[0]}_{i}')
        r['_i'] = i
        recs.append(r)
    if a.sample:
        rng = random.Random(a.seed)
        if a.strata:
            groups = collections.defaultdict(list)
            for r in recs:
                groups[r[a.strata]].append(r)
            per = a.sample // len(groups)
            recs = [r for k in sorted(groups) for r in rng.sample(groups[k], min(per, len(groups[k])))]
        else:
            recs = rng.sample(recs, a.sample)
    t0 = time.time()
    with Pool(a.procs) as pool, open(a.out, 'w') as f:
        for o in pool.imap(work, [(r, a.bans, a.bound, a.time) for r in recs], chunksize=1):
            f.write(json.dumps(o) + '\n'); f.flush()
    print(json.dumps({'in': a.inp, 'n': len(recs), 'bans': a.bans, 'bound': a.bound, 'time': a.time, 'wall_s': round(time.time() - t0, 1)}))


if __name__ == '__main__':
    main()
