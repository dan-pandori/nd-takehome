#!/usr/bin/env python3
"""Phase L selection (pre-registration Part A/B): which correct solutions get scored, and the summary table.

plan   : writes artifacts/olmo_pilot/ll/sel_<model>.txt (keys job|pid|chunk|i of the samples generated by <model>):
         group reach      - every rl-correct sample of an RL checkpoint on one of its reach problems (<= 8 per problem)
         group ckpt_other - <= 2 rl-correct samples per problem of each RL checkpoint on its non-reach headline problems
         group base_own   - <= 2 rl-correct base samples per headline problem the base solved
         and sel_groups.json (key -> group). Seeded random choice within caps.
table  : joins scored files (ll/L_scored_<scorer>_<gen>.jsonl) into olmo_pilot/likelihood.csv and prints the summary,
         including the share of reach solutions whose base mean log-prob per token lies inside the 2.5-97.5 % range of
         the base's own correct solutions ("in the base's support", Part A).
"""
import csv
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

A = Path("artifacts/olmo_pilot")
O = Path("olmo_pilot")


def jobs():
    return list(csv.DictReader(open(O / "jobs.csv")))


def correct_keys(model, phases=("fixed", "confirm", "extension")):
    out = defaultdict(list)
    for j in jobs():
        if j["model"] != model or j["phase"] not in phases:
            continue
        f = A / "graded" / f"{j['job']}.jsonl"
        if not f.exists():
            continue
        for ln in open(f):
            r = json.loads(ln)
            if r["rl"]:
                out[r["pid"]].append(f"{j['job']}|{r['pid']}|{r['chunk']}|{r['i']}")
    return out


def plan():
    rng = random.Random(0)
    excl = {r["pid"] for r in csv.DictReader(open(O / "exclusions.csv"))}
    head = [p for p in open(O / "eval_pids.txt").read().split() if p not in excl]
    reach = {r["model"]: set(r["reach_pids"].split()) for r in csv.DictReader(open(O / "reach.csv")) if r["grade"] == "rl"}
    groups, sel = {}, defaultdict(list)
    for m in sorted({j["model"] for j in jobs()}):
        ck = correct_keys(m)
        for p in head:
            ks = sorted(ck.get(p, []))
            if not ks:
                continue
            if m == "base":
                g, cap = "base_own", 2
            elif p in reach.get(m, set()):
                g, cap = "reach", 8
            else:
                g, cap = "ckpt_other", 2
            for k in rng.sample(ks, min(cap, len(ks))):
                groups[k] = g
                sel[m].append(k)
    (A / "ll").mkdir(parents=True, exist_ok=True)
    for m, ks in sel.items():
        (A / "ll" / f"sel_{m}.txt").write_text("\n".join(ks) + "\n")
    json.dump(groups, open(A / "ll" / "sel_groups.json", "w"))
    cnt = defaultdict(int)
    for g in groups.values():
        cnt[g] += 1
    print(dict(cnt), {m: len(v) for m, v in sel.items()})


def table():
    groups = json.load(open(A / "ll" / "sel_groups.json"))
    sc = defaultdict(dict)  # key -> scorer -> row
    for f in (A / "ll").glob("L_scored_*.jsonl"):
        scorer = f.stem.split("_", 2)[2].rsplit("_", 1)[0]
        for ln in open(f):
            r = json.loads(ln)
            sc[r["key"]][r["model"]] = r
    rows = []
    for k, g in groups.items():
        gen_job, pid = k.split("|")[:2]
        gen = next(j["model"] for j in jobs() if j["job"] == gen_job)
        d = sc.get(k, {})
        if "base" not in d or gen not in d:
            continue
        b, o = d["base"], d[gen]
        rows.append({"key": k, "group": g, "gen_model": gen, "pid": pid, "n_tok": b["n_tok"],
                     "own_mean_lp": round(o["mean_lp"], 5), "base_mean_lp": round(b["mean_lp"], 5),
                     "own_sum_lp": round(o["sum_lp"], 2), "base_sum_lp": round(b["sum_lp"], 2),
                     "base_min_lp": round(b["min_lp"], 3), "base_frac_lt_1e3": round(b["n_lt_1e3"] / b["n_tok"], 5),
                     "own_frac_lt_1e3": round(o["n_lt_1e3"] / o["n_tok"], 5), "base_n_lt_1e6": b["n_lt_1e6"]})
    with open(O / "likelihood.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    own = np.array([r["base_mean_lp"] for r in rows if r["group"] == "base_own"])
    lo, hi = np.percentile(own, [2.5, 97.5]) if len(own) else (np.nan, np.nan)
    print(f"base's own correct solutions: n = {len(own)}, base mean log-prob/token 2.5-97.5 % = [{lo:.3f}, {hi:.3f}]")
    for g in ("reach", "ckpt_other", "base_own"):
        rr = [r for r in rows if r["group"] == g]
        if not rr:
            continue
        gap = np.array([r["own_mean_lp"] - r["base_mean_lp"] for r in rr])
        inside = np.mean([lo <= r["base_mean_lp"] <= hi for r in rr])
        print(f"{g:10s} n={len(rr):3d}  base lp/tok median {np.median([r['base_mean_lp'] for r in rr]):.3f}  "
              f"own {np.median([r['own_mean_lp'] for r in rr]):.3f}  gap median {np.median(gap):.3f} "
              f"[{np.percentile(gap, 10):.3f}, {np.percentile(gap, 90):.3f}]  sum-gap median "
              f"{np.median([r['own_sum_lp'] - r['base_sum_lp'] for r in rr]):.0f} nats  "
              f"in base range {inside:.2f}  base p<1e-3 share {np.median([r['base_frac_lt_1e3'] for r in rr]):.4f}")


if __name__ == "__main__":
    {"plan": plan, "table": table}[sys.argv[1]]()
